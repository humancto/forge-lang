#!/usr/bin/env node
// Regenerates docs/playground/generated.js from sources of truth:
//
//   * GRAMMAR  — word lists from the VS Code TextMate grammar
//                (editors/vscode/syntaxes/forge.tmLanguage.json), so the
//                playground highlights exactly what editors highlight;
//   * EXAMPLES — every examples/*.fg program that runs cleanly in the
//                browser build (checked by actually running it on the
//                WebAssembly module in docs/playground/pkg).
//
//   node bindings/wasm/tools/gen-playground-data.mjs          # write
//   node bindings/wasm/tools/gen-playground-data.mjs --check  # fail if stale
//
// Needs the module built first (bindings/wasm/build.sh).

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const playground = join(repo, "docs", "playground");
const outFile = join(playground, "generated.js");

// ---------------------------------------------------------------- grammar

const grammar = JSON.parse(
  readFileSync(join(repo, "editors", "vscode", "syntaxes", "forge.tmLanguage.json"), "utf8"),
);

/** Words of a `\b(a|b|c)\b` TextMate pattern in repository entry `key`. */
function words(key) {
  const entry = grammar.repository[key];
  const patterns = entry.patterns || [entry];
  const out = new Set();
  for (const p of patterns) {
    const m = /\\b\(([A-Za-z0-9_|]+)\)/.exec(p.match || "");
    if (m) for (const w of m[1].split("|")) out.add(w);
  }
  if (out.size === 0) throw new Error(`no word list in grammar entry '${key}'`);
  return [...out].sort();
}

const GRAMMAR = {
  keywords: words("keywords"),
  natural: [...new Set([...words("natural-keywords"), ...words("innovation-keywords")])].sort(),
  types: words("types"),
  builtins: words("builtins"),
  modules: words("modules"),
  constants: words("constants"),
};

// --------------------------------------------------------------- examples

const { load } = await import(join(playground, "forge.js"));
const forge = await load(readFileSync(join(playground, "pkg", "forge_wasm_bg.wasm")));

// Programs that run but only describe something the browser cannot do.
const NOT_DEMOS = new Map([["mysql_demo.fg", "needs a MySQL server (the program is commented out)"]]);

const examplesDir = join(repo, "examples");
const EXAMPLES = [];
const skipped = [];
for (const file of readdirSync(examplesDir).filter((f) => f.endsWith(".fg")).sort()) {
  if (NOT_DEMOS.has(file)) {
    skipped.push(`${file}: ${NOT_DEMOS.get(file)}`);
    continue;
  }
  const code = readFileSync(join(examplesDir, file), "utf8");
  const result = forge.run(code, {});
  if (forge.crashed) throw new Error(`${file} crashed the module: ${result.error.message}`);
  if (!result.ok) {
    skipped.push(`${file}: ${result.error.message.split("\n")[0]}`);
    continue;
  }
  // Programs that catch the error and carry on are not useful demos.
  const printed = result.stdout + result.stderr;
  const unavailable = /[^\n]*not available in the browser playground[^\n]*/.exec(printed);
  if (unavailable) {
    skipped.push(`${file}: ${unavailable[0].trim()}`);
    continue;
  }
  const firstComment = /^\/\/\s*(?:\S+\.fg\s*[—-]+\s*)?(.+)$/m.exec(code);
  EXAMPLES.push({
    file,
    title: firstComment ? firstComment[1].trim() : file,
    code,
  });
}

// ------------------------------------------------------------------ write

const text =
  "// GENERATED by bindings/wasm/tools/gen-playground-data.mjs — do not edit.\n" +
  "// Regenerate after changing the TextMate grammar or examples/*.fg.\n\n" +
  `export const GRAMMAR = ${JSON.stringify(GRAMMAR, null, 2)};\n\n` +
  `export const EXAMPLES = ${JSON.stringify(EXAMPLES, null, 2)};\n`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outFile, "utf8");
  } catch (_) {}
  if (current !== text) {
    console.error(
      "docs/playground/generated.js is stale: run node bindings/wasm/tools/gen-playground-data.mjs",
    );
    process.exit(1);
  }
  console.log("generated.js is up to date");
} else {
  writeFileSync(outFile, text);
  console.log(`wrote ${outFile}: ${EXAMPLES.length} examples`);
}
for (const s of skipped) console.log(`  not browser-safe: ${s}`);
